/** The texts by language; tests check them against CONTEXT.md. */
export const languages: Record<string, Record<Key, string>> = { en, de };

export type Localize = (key: Key, values?: Record<string, string>) => string;

/** Whether a text exists, for keys built at run time. */
export const hasText = (key: string): key is Key => key in en;

export function localizer(language: string): Localize {
  const texts = languages[language.split("-")[0]] ?? en;
  return (key, values = {}) =>
    texts[key].replace(/\{(\w+)\}/g, (_, name: string) => values[name] ?? "");
}

/** A time still to go: months below a year, else years. */
export function durationText(t: Localize, years: number): string {
  const count = Math.max(1, Math.round(years < 1 ? years * 12 : years));
  return years < 1
    ? t(count === 1 ? "months_one" : "months_other", { count: String(count) })
    : t(count === 1 ? "years_one" : "years_other", { count: String(count) });
}

/** What to say while the integration computes the past, with how far it is. */
export const calculatingText = (t: Localize, progress: number | null): string =>
  progress === null
    ? t("calculating")
    : t("calculating_progress", { percent: String(progress) });
